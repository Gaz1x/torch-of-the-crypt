// Пока уровень только показывает полоску опыта. Позже именно здесь появится
// выбор улучшений при повышении уровня.
// ============================================================================

/** Сколько опыта нужно, чтобы перейти с текущего уровня на следующий. */
export function xpToNextLevel(level: number): number {
  return 8 + level * 4;
}
